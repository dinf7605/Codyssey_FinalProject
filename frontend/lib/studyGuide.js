const CONCEPT = {
  kind: '개념 학습',
  steps: ['교재 · 강의에서 이 단원 부분을 찾아 목차 훑기', '핵심 개념을 읽고 내 말로 3줄 요약', '예제 2~3개로 확인하고 모르는 점은 메모'],
  ratio: [0.1, 0.65, 0.25],
};

// 5분 단위로 나누고, 반올림 오차는 가운데(본 공부) 단계에 몰아 합을 맞춘다
function split(minutes, ratio) {
  const parts = ratio.map((r) => Math.max(5, Math.round((minutes * r) / 5) * 5));
  parts[1] += minutes - parts.reduce((a, b) => a + b, 0);
  return parts;
}

export function studyGuide(title = '', minutes = 0) {
  const found = KINDS.find((k) => k.match.test(title)) || CONCEPT;
  const parts = minutes >= 20 ? split(minutes, found.ratio) : null;
  return {
    kind: found.kind,
    steps: found.steps.map((text, i) => ({ text, minutes: parts ? parts[i] : null })),
  };
}
